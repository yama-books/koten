function detect(text, level){
  const found=[];
  ALL_RULES.forEach((r, ruleIndex)=>{
    let start=0;
    while(true){
      const i=text.indexOf(r.pattern,start);
      if(i<0) break;
      if(!r.guard || r.guard(text,i)) found.push({...r,start:i,end:i+r.pattern.length,ruleIndex,tier:tierForRule(r)});
      start=i+Math.max(1,r.pattern.length);
    }
  });
  detectKanaCandidates(text, level).forEach((r,idx)=>found.push({...r,ruleIndex:ALL_RULES.length+idx}));
  const unique=[]; const seen=new Set(); let basicSuppressed=0;
  for(const f of found){
    if(insideBasicWord(text,f,level)){ basicSuppressed++; continue; }
    const k=`${f.start}:${f.end}:${f.type}:${f.pattern}:${f.lemma||""}`;
    if(seen.has(k)) continue; seen.add(k); unique.push(f);
  }
  unique.sort((a,b)=>a.start-b.start || (b.end-b.start)-(a.end-a.start) || a.tier-b.tier);
  return {hits:unique,basicSuppressed};
}

