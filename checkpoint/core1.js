// 1 = 重要識別・重要敬語
// 2 = 標準
// 3 = 助詞・活用形などの細部
// 4 = 基本語彙まで広げる
// 5 = 弱い部分一致までデバッグ的に見る
const TIER_1 = new Set(["ぬ","なむ","なり","に","ば","らむ","けれ","しか","たり","にて","ばや","せ","む","べけれ"]);
const TIER_2 = new Set(["が","して","とも","ね","けり","べし","やうやう","ぎは","をかし","あはれ"]);
const TIER_3 = new Set(["て","を","と","し","る","な"]);
const TIER_4 = new Set(["日ごと","しばし","もし","たちまち","いよいよ"]);

function tierForRule(r){
  if(r.tierOverride) return r.tierOverride;
  if(TIER_1.has(r.pattern)) return 1;
  if(TIER_2.has(r.pattern)) return 2;
  if(TIER_3.has(r.pattern)) return 3;
  if(TIER_4.has(r.pattern)) return 4;
  if(r.type==="honorific") return 1;
  if(r.type==="identify") return r.pattern.length >= 2 ? 2 : 5;
  if(r.type==="grammar") return 2;
  if(r.type==="vocab") return 4;
  return 3;
}

const BASIC_WORDS = [
  "すこし","しばし","もし","いつも","たちまち","いよいよ",
  "参る","参り","入る","入り","見る","見れ","あり","ある",
  "候ふ","候は","候へ","給ふ","給ひ","奉る","奉り",
  "取り","取る","知る","降り","寄せ","尋ね","思ひ"
];

function insideBasicWord(text, hit, level){
  if(String(level)==="5") return false;
  if(hit.pattern.length > 1) return false;
  for(const w of BASIC_WORDS){
    let pos = 0;
    while(true){
      const i = text.indexOf(w, pos);
      if(i < 0) break;
      const j = i + w.length;
      if(hit.start >= i && hit.end <= j && (hit.start > i || hit.end < j)) return true;
      pos = i + 1;
    }
  }
  return false;
}

