import type { EventMethod } from '../event.ts';

export const POINTS_RULES_VERSION = 1 as const;

/**
 * 「やったぶんはやったぶんだけたまる」ための積算値（依頼者裁定・2026-09-09）。
 *
 * 習熟度が**飽和する残高**であるのに対し、ポイントは**飽和しない積算**である。
 * 習熟度100の歌をもう一度解いてもポイントは増える。逆に、ポイントが増えても
 * 習熟度は1も動かない。二つを混ぜないこと。
 *
 * **計算規則は生徒に開示しない。** 開示すると「習熟度の低い歌を探して解く」のが
 * 最適戦略になり、素直に解いた生徒が損をする。画面に出すのは獲得点と累計だけで、
 * 基礎点も倍率もどこにも表示しない。
 */

/** 正答および自己評価・閲覧で得る基礎点。難しい方式ほど高い。 */
export const EARNED_POINTS: Readonly<Record<EventMethod, number>> = {
  view: 3,
  'self-x': 3,
  'self-tri': 6,
  'self-o': 8,
  choice: 10,
  'kanji-to-kana': 12,
  'free-input': 14,
  'paper-handwriting': 14,
};

/**
 * 誤答。**0にしない。** 0にすると「全問まちがえた回は、やったのに何も増えない」となり、
 * 「やったぶんはやったぶんだけたまる」という裁定と正面から衝突する。
 * ただし選択式正答の 1/3 以下に抑え、当てずっぽうが得にならないようにする。
 */
export const ATTEMPT_POINTS = 3;

/**
 * 弱点倍率の上限。習熟度0の歌で 2.0、習熟度100の歌で 1.0。
 *
 * 2倍で止める理由：これ以上開くと、覚えた歌をもう一度確かめる行動が**損**に感じられる。
 * 復習に罰を与えるのはこの教材では逆効果である。
 */
export const MAX_WEAKNESS_MULTIPLIER = 2;

/** 同一セッション内で同じ問題を繰り返したときの係数。習熟度側の増分半減に合わせる。 */
export const REPEAT_FACTOR = 0.5;

/**
 * **難しい段ほど、ポイントが少し高くつく**（依頼者・2026-09-15）。
 *
 * これまで基礎点は方式だけで決まり、**段を見ていなかった**——一句を書くのも
 * 一首まるごと書くのも同じ 14 点だった。書く量は 5 倍違う。
 *
 * **分量の比そのままにはしない。** 段7 は段3 の 5 倍を書くが係数は 2.2 に圧縮する
 * ——弱点倍率を 2 倍で止めたのと同じ理由で、開きすぎると易しい復習が「損」に感じられる。
 *
 * **段8 が一番高い。** 番号だけを手がかりに一首を書く段で、**習熟度は動かない**
 * （`RUNG_CAPS` に天井が無い）。ポイントだけが報酬になるので、ここを低くすると
 * 完全制覇へ挑む理由が無くなる。
 *
 * **易しい段は罰ではない。** 段1 を解くのはたいてい習熟度の低い学習者で、
 * そちらは弱点倍率（最大2.0）が効く——初学者の段1 は、上級者の段3 より高くつく。
 */
export const RUNG_POINT_FACTOR: Readonly<Record<number, number>> = {
  1: 0.7, 2: 0.85, 3: 1, 4: 1.4, 5: 1.7, 6: 2, 7: 2.2, 8: 2.5,
};
